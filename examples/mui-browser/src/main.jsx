import React, { useRef, useState } from 'react';
import { createRoot } from 'react-dom/client';
import {
  Alert, Box, Button, Chip, Container, CssBaseline, Dialog, DialogActions,
  DialogContent, DialogContentText, DialogTitle, Divider, Paper, Stack,
  TextField, ThemeProvider, Typography, createTheme,
} from '@mui/material';
import tokens from '../../../packages/tokens/tokens.json';
import GeneratedButton from './GeneratedButton';

const theme = createTheme({
  palette: {
    primary: { main: tokens.color.action.primary, contrastText: tokens.color.action.onPrimary },
    background: { default: tokens.color.surface.subtle, paper: tokens.color.surface.default },
    text: { primary: tokens.color.text.primary, secondary: tokens.color.text.secondary },
  },
  spacing: tokens.spacing.unit,
  shape: { borderRadius: tokens.radius.control },
  typography: { fontFamily: 'Inter, system-ui, sans-serif' },
  components: {
    MuiButton: { styleOverrides: { root: {
      minHeight: 44, textTransform: 'none', fontWeight: 600,
      '&.Mui-focusVisible': { outline: `3px solid ${tokens.color.focus.ring}`, outlineOffset: 3 },
    } } },
  },
});

function App() {
  const [name, setName] = useState('');
  const [savedName, setSavedName] = useState('');
  const [error, setError] = useState(false);
  const [resetOpen, setResetOpen] = useState(false);
  const inputRef = useRef(null);
  const dirty = name !== savedName;
  function save(event) {
    event.preventDefault();
    if (!name.trim()) {
      setError(true);
      inputRef.current?.focus();
      return;
    }
    setName(name.trim());
    setSavedName(name.trim());
    setError(false);
  }
  function reset() {
    setName('');
    setSavedName('');
    setError(false);
    setResetOpen(false);
  }
  return (
    <Container component="main" maxWidth="md" sx={{ py: { xs: 8, sm: 16 } }}>
      <Stack spacing={6}>
        <Stack direction="row" spacing={2} alignItems="center" flexWrap="wrap" useFlexGap>
          <Typography fontWeight={800} letterSpacing="0.1em">B.A.R</Typography>
          <Chip label="Experimental example" size="small" variant="outlined" />
        </Stack>
        <Box>
          <Typography variant="h3" component="h1" fontWeight={750} sx={{ fontSize: { xs: '2rem', sm: '3rem' } }}>
            Small interface. Real checks.
          </Typography>
          <Typography color="text.secondary" sx={{ mt: 3, maxWidth: 560 }}>
            A working MUI form, styled with B.A.R tokens and checked in a real browser.
            No account, network request or persistent storage is involved.
          </Typography>
        </Box>
        <Paper variant="outlined" sx={{ p: { xs: 5, sm: 8 } }}>
          <Stack component="form" noValidate onSubmit={save} spacing={5} aria-labelledby="preferences-heading">
            <Box>
              <Typography id="preferences-heading" variant="h5" component="h2" fontWeight={700}>Your workspace</Typography>
              <Typography color="text.secondary" sx={{ mt: 2 }}>Try saving a name, then use the keyboard to reset it.</Typography>
            </Box>
            <TextField label="Display name" value={name} inputRef={inputRef} required fullWidth
              error={error} helperText={error ? 'Enter a display name before saving.' : 'Stored only in this page until you reload.'}
              onChange={(event) => { setName(event.target.value); setError(false); }}
              slotProps={{ htmlInput: { maxLength: 80, autoComplete: 'nickname' } }} />
            <Stack direction={{ xs: 'column', sm: 'row' }} spacing={3}>
              <Button type="submit" variant="contained" disabled={Boolean(savedName) && !dirty}>Save preferences</Button>
              <Button type="button" variant="outlined" onClick={() => setResetOpen(true)} disabled={!name && !savedName}>Reset example</Button>
            </Stack>
            <Box role="status" aria-live="polite" aria-atomic="true">
              {savedName && <Alert severity="success">Saved for this session: {savedName}</Alert>}
            </Box>
          </Stack>
        </Paper>
        <Paper variant="outlined" sx={{ p: { xs: 5, sm: 8 } }}>
          <Stack spacing={4}>
            <Typography variant="h6" component="h2">BUILD output</Typography>
            <Typography color="text.secondary">This button is generated by the existing CLI engine. It is a template, not a wired application action.</Typography>
            <Box><GeneratedButton /></Box>
            <Divider />
            <Typography variant="body2" color="text.secondary">Automated checks support review. They do not certify accessibility or implement automatic repairs.</Typography>
          </Stack>
        </Paper>
      </Stack>
      <Dialog open={resetOpen} onClose={() => setResetOpen(false)} aria-labelledby="reset-title" aria-describedby="reset-description">
        <DialogTitle id="reset-title">Reset this example?</DialogTitle>
        <DialogContent><DialogContentText id="reset-description">This clears the name saved in this page. Nothing outside this example changes.</DialogContentText></DialogContent>
        <DialogActions>
          <Button onClick={() => setResetOpen(false)} autoFocus>Cancel</Button>
          <Button onClick={reset}>Reset now</Button>
        </DialogActions>
      </Dialog>
    </Container>
  );
}

createRoot(document.getElementById('root')).render(<React.StrictMode><ThemeProvider theme={theme}><CssBaseline /><App /></ThemeProvider></React.StrictMode>);
