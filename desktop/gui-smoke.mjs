// Exercise the actual Electron application (unpacked or installed).
import {_electron as electron,expect} from '@playwright/test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const output=path.resolve('desktop-test-results');fs.mkdirSync(output,{recursive:true});
const checks=[];
const root=fs.mkdtempSync(path.join(os.tmpdir(),'bar-desktop-smoke-'));
const original='export default () => <img data-bar-decorative="true" src="x" />;\n';
fs.writeFileSync(path.join(root,'Card.tsx'),original);
fs.writeFileSync(path.join(root,'styles.css'),'.card { color: #123456; color: #123456; }');
const report=path.join(root,'report.json');
const env={...process.env,BAR_DESKTOP_TEST:'1',BAR_TEST_PROJECT:root,BAR_TEST_EXPORT_PATH:report,BAR_TEST_CONFIRM:'1'};
delete env.ELECTRON_RUN_AS_NODE;
const executablePath=process.env.BAR_DESKTOP_EXECUTABLE;
const application=await electron.launch({...(executablePath?{executablePath}:{}),args:[...(!executablePath?['desktop/main.mjs']:[]),'--bar-desktop-test'],env,timeout:60000});
try {
 const page=await application.firstWindow();
 const runtime=await application.evaluate(()=>({...process.versions}));
 if(runtime.electron!=='45.1.0'||runtime.node!=='24.22.1')throw Error('Unexpected embedded runtime');
 await expect(page.getByRole('heading',{name:'Choose your workspace'})).toBeVisible();
 await page.getByRole('button',{name:'Choose project folder'}).click();
 await expect(page.locator('#root')).toHaveText(root);
 await application.evaluate(()=>{delete process.env.BAR_TEST_PROJECT;});
 await page.getByRole('button',{name:'Choose project folder'}).click();
 await expect(page.locator('#status')).toHaveText('Folder selection cancelled.');
 await expect(page.locator('#root')).toHaveText(root);
 checks.push('cancelled folder dialog preserves selection');
 await page.getByRole('button',{name:'Run source + CSS audit'}).click();
 await expect(page.locator('#status')).toContainText('Audit finished',{timeout:30000});
 await expect(page.locator('#results')).toContainText('Source findings');
 await page.getByRole('button',{name:'Export JSON report'}).click();
 await expect(page.locator('#status')).toContainText('Report saved');
 if(!JSON.parse(fs.readFileSync(report,'utf8')).source.summary.files)throw Error('Export missing findings');
 await page.getByRole('button',{name:'Preview supported repairs'}).click();
 await expect(page.locator('#status')).toContainText('1 file(s) have supported repairs');
 if(fs.readFileSync(path.join(root,'Card.tsx'),'utf8')!==original)throw Error('Preview wrote source');
 await expect(page.locator('#changes')).toContainText('Card.tsx');
 await page.screenshot({path:path.join(output,'desktop-preview.png'),fullPage:true});
 await page.getByRole('button',{name:'Export JSON report'}).click();
 await expect(page.locator('#status')).toContainText('Report saved');
 if(!JSON.parse(fs.readFileSync(report,'utf8')).css)throw Error('Preview discarded full CSS report');
 checks.push('preview preserves full audit export');
 await application.evaluate(()=>{process.env.BAR_TEST_CONFIRM='0';});
 await page.getByRole('button',{name:'Apply previewed repairs'}).click();
 await expect(page.locator('#status')).toContainText('Apply cancelled');
 if(fs.readFileSync(path.join(root,'Card.tsx'),'utf8')!==original)throw Error('Cancelled apply wrote source');
 await expect(page.locator('#changes')).toContainText('Card.tsx');
 await page.getByRole('button',{name:'Export JSON report'}).click();
 await expect(page.locator('#status')).toContainText('Report saved');
 if(!JSON.parse(fs.readFileSync(report,'utf8')).css)throw Error('Preview discarded full CSS report');
 checks.push('preview preserves full audit export');
 await application.evaluate(()=>{process.env.BAR_TEST_CONFIRM='1';});
 checks.push('cancelled apply preserves source and preview');
 const edited=original+'// external edit\n';
 fs.writeFileSync(path.join(root,'Card.tsx'),edited);
 await page.getByRole('button',{name:'Apply previewed repairs'}).click();
 await expect(page.locator('#error')).toContainText('Stale file');
 await expect(page.getByRole('button',{name:'Apply previewed repairs'})).toBeDisabled();
 if(fs.readFileSync(path.join(root,'Card.tsx'),'utf8')!==edited)throw Error('Stale apply overwrote external edits');
 fs.writeFileSync(path.join(root,'Card.tsx'),original);
 await page.getByRole('button',{name:'Preview supported repairs'}).click();
 await expect(page.locator('#status')).toContainText('1 file(s) have supported repairs');
 checks.push('stale apply refuses external edits and invalidates preview');
 await page.getByRole('button',{name:'Apply previewed repairs'}).click();
 await expect(page.locator('#status')).toContainText('Applied repairs to 1 file(s)');
 if(fs.readFileSync(path.join(root,'Card.tsx'),'utf8')===original)throw Error('Apply did not write');
 await page.getByRole('button',{name:'Undo selected repair'}).click();
 await expect(page.locator('#status')).toContainText('Restored 1 file(s)');
 if(fs.readFileSync(path.join(root,'Card.tsx'),'utf8')!==original)throw Error('Undo did not restore bytes');
 // Renderer has no raw Node or Electron privileges.
 if(await page.evaluate(()=>typeof window.require!=='undefined'||typeof window.process!=='undefined'))throw Error('Renderer leaked Node');
 await page.screenshot({path:path.join(output,'desktop-restored.png'),fullPage:true});
 const interrupted=await page.evaluate(async()=>{const pending=window.bar.run('audit');const busy=await window.bar.choose();const cancelled=await window.bar.cancel();return {busy,cancelled,result:await pending};});
 if(interrupted.busy.ok||!interrupted.cancelled.ok||interrupted.result.ok)throw Error('Busy/cancel contract failed');
 checks.push('busy guard and cancellable scan');
 const denied=await page.evaluate(()=>window.bar.run('arbitrary-command'));
 if(denied.ok)throw Error('Unsupported IPC action accepted');
 fs.writeFileSync(path.join(root,'Invalid.tsx'),'const = ;');
 await page.getByRole('button',{name:'Run source + CSS audit'}).click();
 await expect(page.locator('#status')).toContainText('Audit incomplete');
 await page.getByRole('button',{name:'Preview supported repairs'}).click();
 await expect(page.locator('#error')).toContainText('source errors');
 const stale=await page.evaluate(()=>window.bar.run('apply'));
 if(stale.ok||!stale.error.includes('Preview repairs first')||!stale.journals?.length)throw Error('Failed preview retained plan or omitted recovery journals');
 checks.push('failed preview invalidates plan and error returns recovery journals');
 await page.screenshot({path:path.join(output,'desktop-error.png'),fullPage:true});
 checks.push('selection','source and CSS audit','JSON export','read-only preview','apply','byte-exact undo','renderer isolation','invalid IPC rejected','source error feedback');
 fs.writeFileSync(path.join(output,'gui-report.json'),JSON.stringify({passed:true,checks,runtime,projectRoot:root,fixtureFile:'Card.tsx',originalFixture:original},null,2));
 console.log('Desktop GUI smoke passed: selection, audit, export, preview, apply, undo, isolation, errors.');
}catch(error){fs.writeFileSync(path.join(output,'gui-report.json'),JSON.stringify({passed:false,checks,error:error.message,projectRoot:root},null,2));throw error;}finally{await application.close();if(process.env.BAR_TEST_KEEP_PROJECT!=='1')fs.rmSync(root,{recursive:true,force:true});}
